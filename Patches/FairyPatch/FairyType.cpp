extern "C" EFFECTIVENESS THUMB_BRANCH_GetTypeEffectiveness(POKE_TYPE moveType, POKE_TYPE pokeType) {
    if (moveType >= TYPE_NULL || pokeType >= TYPE_NULL) {
        return EFFECTIVENESS_1;
    }

    const u8* typeChart = TYPE_CHART;   // W1: embedded, no file read at runtime
    {
        switch (typeChart[TYPE_NULL * moveType + pokeType]) {
        case NOT_EFFECTIVE: {
            return EFFECTIVENESS_IMMUNE;
        }
        case NOT_VERY_EFFECTIVE: {
            return EFFECTIVENESS_1_2;
        }
        case EFFECTIVE: {
            return EFFECTIVENESS_1;
        }
        case SUPER_EFFECTIVE: {
            return EFFECTIVENESS_2;
        }
        default: {
            return EFFECTIVENESS_IMMUNE;
        }
        }
    }
    return EFFECTIVENESS_1;
}

extern "C" s32 THUMB_BRANCH_GetTypeWeaknesses(POKE_TYPE type, u8* weakness) {
    if (type >= TYPE_NULL) {
        return 0;
    }

    const u8* typeChart = TYPE_CHART;   // W1: embedded, no file read at runtime
    {
        u32 weaknessIdx = 0;
        u32 row = TYPE_NULL * type;

        for (u32 i = 0; i < TYPE_NULL; ++i) {
            if (!typeChart[row + i] || 
                typeChart[row + i] == NOT_VERY_EFFECTIVE) {
                weakness[weaknessIdx++] = i;
            }
        }
        return weaknessIdx;
    }
    return 0;
}

extern "C" u32 THUMB_BRANCH_GetPokemonTypeIconPalette(POKE_TYPE type)
{
    // W1: the vanilla function (0x2027604) is a simple table[type] lookup @0x0209FD10.
    // The original PW2Code hook did ReadByteFromFile on EVERY type-icon render → the runtime
    // romfs crashes on W1 (same reason as the static TYPE_CHART above) → freeze. Here we read
    // the SAME palette table already in RAM. BUT for Fairy (17) the arm9 entry @0x0209FD21 does
    // not apply (returns 0 = sub0 = FIGHTING) → the move-menu type box showed Fighting colors.
    // W2 (which reads type_palette_map.bin[17]=2) uses sub 2, which ALREADY HAS the Fairy colors
    // (idx8=#ef9ee7 pink, idx9=#793e74 mauve). W1 fix: return 2 for Fairy (like W2), zero palette
    // edit, zero conflict with Fighting.
    if ((u32)type == 17) return 2;  // sub2 = Fairy colors (like W2 type_palette_map.bin[17]=2)
    return ((const u8*)0x0209FD10)[(u32)type];
}

